#define BC 8
#define ROUNDS 14

// 单块解密, 完全镜像 py3rijndael.Rijndael.decrypt
static void decrypt_block_256(const uint8_t *in, uint8_t *out) {
    uint32_t t[BC], a[BC];
    const int s1 = 7, s2 = 5, s3 = 4;  // shifts[2] 解密位移
    for (int i = 0; i < BC; i++) {
        t[i] = ((uint32_t)in[i*4] << 24) | ((uint32_t)in[i*4+1] << 16) |
               ((uint32_t)in[i*4+2] << 8) | (uint32_t)in[i*4+3];
        t[i] ^= KD[0][i];
    }
    for (int r = 1; r < ROUNDS; r++) {
        for (int i = 0; i < BC; i++) {
            a[i] = T5[(t[i] >> 24) & 0xFF] ^
                   T6[(t[(i + s1) % BC] >> 16) & 0xFF] ^
                   T7[(t[(i + s2) % BC] >> 8) & 0xFF] ^
                   T8[t[(i + s3) % BC] & 0xFF] ^
                   KD[r][i];
        }
        memcpy(t, a, sizeof(t));
    }
    for (int i = 0; i < BC; i++) {
        uint32_t tt = KD[ROUNDS][i];
        out[i*4]   = (uint8_t)(Si[(t[i] >> 24) & 0xFF] ^ (tt >> 24));
        out[i*4+1] = (uint8_t)(Si[(t[(i + s1) % BC] >> 16) & 0xFF] ^ (tt >> 16));
        out[i*4+2] = (uint8_t)(Si[(t[(i + s2) % BC] >> 8) & 0xFF] ^ (tt >> 8));
        out[i*4+3] = (uint8_t)(Si[t[(i + s3) % BC] & 0xFF] ^ tt);
    }
}

// 就地 CBC 解密 (IV = 游戏 IV, 固定). len 须为 32 的倍数.
int rijndael256_cbc_decrypt(uint8_t *data, size_t len, const uint8_t *key32, const uint8_t *iv32) {
    uint8_t prev[32], cur[32];
    memcpy(prev, iv32, 32);
    for (size_t i = 0; i + 32 <= len; i += 32) {
        memcpy(cur, &data[i], 32);
        uint8_t out[32];
        decrypt_block_256(cur, out);
        for (int j = 0; j < 32; j++) data[i + j] = out[j] ^ prev[j];
        memcpy(prev, cur, 32);
    }
    return 0;
}
